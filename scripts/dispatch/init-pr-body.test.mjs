// @vitest-environment node
import { expect, it } from 'vitest'
import { readFileSync } from 'node:fs'
import path from 'node:path'
import { composePullRequestBody } from './init-pr-body.mjs'
import { callerState, makeRepo, pullWrites, runInit, setUpInitFixture } from './init-fixture.mjs'

setUpInitFixture()

const FACTS = {
  repo: 'acme/widgets', branch: 'steward/install', baseSha: 'b'.repeat(40),
  version: '1.2.3', pin: `at commit ${'a'.repeat(40)}`, workflowsAdded: true,
  added: [{ rel: 'steward.config.json', note: 'generated project settings' }],
  preserved: ['.github/workflows/review-gate.yml'], land: false, emptyTemplates: [],
  checks: ['Inventory: original byte content. Passed.'],
}
const EXAMPLE = '<!--\n## What changed\n## Verification\n-->\nUnit:\n## Summary\n'
// An independent visibility assertion for HTML-comment fixtures, including unfinished comments.
const withoutComments = (body) => body.replace(/<!--(?:[\s\S]*?-->|[\s\S]*$)/g, '')
const compose = (skeleton) => composePullRequestBody({ skeleton, facts: FACTS })

function expectVisibleFacts(body, version = '1.2.3') {
  const visible = withoutComments(body)
  for (const text of ['steward.config.json', 'Left as they were', `Generated by steward v${version}.`,
    'Installation workflow target:', 'Checks `steward init` ran', 'All Git hooks were disabled',
    'Before the crew marks it ready:', 'Merging this starts nothing', 'did not check or change the project']) {
    expect(visible).toContain(text)
  }
}

it.each([['LF', '\n'], ['CRLF', '\r\n']])('ST-56/AC-6: commented example headings stay visible through the fallback summary (%s)', (_label, eol) => {
  const skeleton = EXAMPLE.replaceAll('\n', eol)
  const body = compose(skeleton)
  expect(body).toContain(`<!--${eol}## What changed${eol}## Verification${eol}-->`)
  expectVisibleFacts(body)
  const visible = withoutComments(body)
  for (const label of ['**What changed**', '**Verification**', '**Docs check**']) expect(visible).toContain(label)
  expect(visible).toMatch(/^Unit: none/m)
  expect(visible.match(/## Installation summary/g)).toHaveLength(1)
  expect(body.replaceAll(eol, '')).not.toMatch(/[\r\n]/)
})

it('ST-56/AC-6: commented headings inside visible sections do not hide the inserted blocks', () => {
  const comment = '<!-- project instructions\n## Verification\n## Docs check\n-->'
  const skeleton = `Unit:\n## What changed\n${comment}\n\n## Verification\n<!-- check prompt -->\n\n## Docs check\n<!-- docs prompt -->\n`
  const body = compose(skeleton)
  expect(body).toContain(comment)
  expectVisibleFacts(body)
  const visible = withoutComments(body)
  expect(visible).not.toContain('Installation summary')
  expect(visible.indexOf('Generated by steward')).toBeLessThan(visible.indexOf('## Verification'))
  expect(visible.indexOf('Checks `steward init` ran')).toBeLessThan(visible.indexOf('## Docs check'))
})

it('ST-56/AC-6: inline heading comments and indented visible headings retain their prompts', () => {
  const skeleton = 'Unit:\n## What <!-- keep this -->changed\n  ## Verification <!-- check prompt -->\n### Docs check\n'
  const body = compose(skeleton)
  expect(body).toContain('## What <!-- keep this -->changed')
  expect(body).toContain('  ## Verification <!-- check prompt -->')
  expectVisibleFacts(body)
  expect(withoutComments(body)).not.toContain('Installation summary')
})

it('ST-56/AC-6: hidden Unit lines and checkboxes remain examples, and inline Unit comments are preserved', () => {
  const hidden = '<!--\nUnit: #example\n- [ ] hidden checkbox\n## Hidden instructions\n-->'
  const inline = '<!-- Keep the issue-link prompt. -->'
  const body = compose(`${hidden}\nUnit: #crew ${inline}\n- [ ] visible checkbox\n## Summary\n`)
  expect(body).toContain(hidden)
  expect(body).toContain(inline)
  const visible = withoutComments(body)
  expect(visible).toMatch(/^Unit: none[ \t]*$/m)
  expect(visible).toContain('Tick or remove the 1 unchecked item')
  expect(visible).not.toContain('`## Hidden instructions`')
  expectVisibleFacts(body)
})

it('ST-56/AC-6: generated facts precede an unfinished trailing comment instead of becoming hidden', () => {
  const tail = '<!-- unfinished project prompt\n## Verification\n'
  const body = compose(`Unit:\n## What changed\n${tail}`)
  expect(body.endsWith(tail)).toBe(true)
  expectVisibleFacts(body)
  expect(withoutComments(body)).toContain('**Verification**')
  expect(body.indexOf('Generated by steward')).toBeLessThan(body.indexOf('<!-- unfinished'))
})

it('ST-56/AC-6: fenced examples are not sections and literal HTML markers in them do not hide real sections', () => {
  const example = '```markdown\n<!-- literal example\n## What changed\n## Verification\nUnit: #example\n- [ ] example\n```'
  const body = compose(`${example}\nUnit:\n## What changed\n## Verification\n## Docs check\n`)
  expect(body).toContain(example)
  expect(body).not.toContain('Installation summary')
  expect(body.indexOf('Generated by steward')).toBeGreaterThan(body.lastIndexOf('```'))
  expect(body).not.toContain('unchecked item')
  expect(body).toContain('\nUnit: none\n')
})

it.each(['Use `<!--` as the literal marker.', 'Use \\<!-- as the escaped marker.'])('ST-56/AC-6: literal comment markers in a prompt preserve visible sections: %s', (prompt) => {
  const body = compose(`Unit:\n${prompt}\n## What changed\n## Verification\n## Docs check\n`)
  expect(body).toContain(prompt)
  expect(body).not.toContain('Installation summary')
  expect(body.indexOf('Generated by steward')).toBeGreaterThan(body.indexOf('## What changed'))
})

it.each([['LF', '\n'], ['CRLF', '\r\n']])('ST-56/AC-6: real init publishes visible facts from a commented template without editing it (%s)', async (_label, eol) => {
  const template = EXAMPLE.replaceAll('\n', eol)
  const rel = '.github/pull_request_template.md'
  const cwd = makeRepo({ files: { [rel]: template } })
  const before = callerState(cwd)
  const r = await runInit(['--yes'], { cwd })
  expect(r.code, r.err).toBe(0)
  const body = pullWrites(r.gh)[0].body.body
  expectVisibleFacts(body, '9.8.7')
  expect(withoutComments(body)).toContain('**What changed**')
  expect(withoutComments(body)).toContain('**Verification**')
  expect(body).toContain(`<!--${eol}## What changed${eol}## Verification${eol}-->`)
  expect(readFileSync(path.join(cwd, ...rel.split('/')), 'utf8')).toBe(template)
  expect(callerState(cwd)).toEqual(before)
})
